function getCurrentLang() {
    return localStorage.getItem('siteLang') || 'en';
}

function setCurrentLang(lang) {
    localStorage.setItem('siteLang', lang);
    updateLangIndicator();
    translatePage();
    document.dispatchEvent(new Event('languagechange'));
}

function t(key) {
    const lang = getCurrentLang();
    return (translations[lang] && translations[lang][key]) || translations.en[key] || key;
}

function translateElement(el) {
    const key = el.dataset.i18n;
    if (!key) return;
    const field = el.dataset.i18nAttr || 'textContent';
    const value = t(key);
    if (field === 'textContent') el.textContent = value;
    else el.setAttribute(field, value);
}

function translatePage(root = document) {
    const nodes = root.querySelectorAll('[data-i18n]');
    nodes.forEach(translateElement);
    const placeholders = root.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    const titles = root.querySelectorAll('[data-i18n-title]');
    titles.forEach(el => { el.title = t(el.dataset.i18nTitle); });
    const ariaLabels = root.querySelectorAll('[data-i18n-aria-label]');
    ariaLabels.forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel)); });
    const values = root.querySelectorAll('[data-i18n-value]');
    values.forEach(el => { el.value = t(el.dataset.i18nValue); });
    if (root === document) document.documentElement.lang = getCurrentLang();
}

function updateLangIndicator() {
    const button = document.getElementById('langToggle');
    if (button) {
        button.dataset.lang = getCurrentLang();
    }
}

function initI18n() {
    updateLangIndicator();
    translatePage();
    const button = document.getElementById('langToggle');
    if (button) {
        button.addEventListener('click', () => {
            const nextLang = getCurrentLang() === 'en' ? 'ka' : 'en';
            setCurrentLang(nextLang);
            translatePage();
            updateLangIndicator();
        });
    }
}

document.addEventListener('DOMContentLoaded', initI18n);
